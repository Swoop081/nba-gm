import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const files=[path.join(root,'data','league.js'),...fs.readdirSync(path.join(root,'data','teams')).filter(x=>x.endsWith('.js')).map(x=>path.join(root,'data','teams',x))];
const players=new Map();
for(const file of files){
  const s=fs.readFileSync(file,'utf8');
  for(const m of s.matchAll(/P\(\s*(\d+)\s*,\s*['"]([^'"]+)['"]\s*,\s*['"][^'"]+['"]\s*,\s*\d+\s*,\s*['"][^'"]+['"]\s*,\s*(\d+)/g)) players.set(+m[1],{nbaId:+m[1],name:m[2],exp:+m[3]});
  for(const m of s.matchAll(/\{\s*nbaId\s*:\s*(\d+)\s*,\s*name\s*:\s*['"]([^'"]+)['"][\s\S]{0,180}?exp\s*:\s*(\d+)/g)) players.set(+m[1],{nbaId:+m[1],name:m[2],exp:+m[3]});
}
const roster=[...players.values()].sort((a,b)=>a.name.localeCompare(b.name));
const veteran=roster.filter(p=>p.exp>0),rookie=roster.filter(p=>p.exp===0);
const seasons=[2026,2025,2024,2023];
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function highs(p){
 for(const season of seasons){
  const url=`https://data.nba.com/data/v2022/json/mobile_teams/nba/${season}/players/player_highs_${p.nbaId}_02.json`;
  try{
   const r=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0'}});
   if(!r.ok) continue;
   const j=await r.json(),ca=j?.data?.pl?.ca;
   if(!ca) continue;
   const out={pts:Number(ca.pts?.val),reb:Number(ca.reb?.val),ast:Number(ca.ast?.val),stl:Number(ca.stl?.val),blk:Number(ca.blk?.val),tpm:Number(ca.tpm?.val)};
   if(Object.values(out).every(Number.isFinite)) return out;
  }catch{}
 }
 return null;
}
const out={},failed=[];
for(let i=0;i<veteran.length;i++){
 const p=veteran[i],v=await highs(p);
 if(v) out[p.nbaId]=v; else failed.push(p);
 process.stdout.write(`\rVerified ${i+1}/${veteran.length}; missing ${failed.length}`);
 await sleep(80);
}
for(const p of rookie) out[p.nbaId]={pts:0,reb:0,ast:0,stl:0,blk:0,tpm:0};
console.log(`\nRoster ${roster.length}; veterans ${veteran.length}; rookies ${rookie.length}; verified veterans ${veteran.length-failed.length}; missing ${failed.length}`);
if(failed.length){console.error('MISSING:',failed.map(p=>`${p.name} (${p.nbaId})`).join(', '));process.exitCode=2;}
const body='// Generated by scripts/build-career-highs.mjs. Do not hand-edit.\nexport const CAREER_HIGHS='+JSON.stringify(out,null,2)+';\n';
fs.writeFileSync(path.join(root,'data','career-highs.js'),body);
fs.writeFileSync(path.join(root,'data','career-highs-audit.json'),JSON.stringify({generatedAt:new Date().toISOString(),roster:roster.length,veterans:veteran.length,rookies:rookie.length,verifiedVeterans:veteran.length-failed.length,missing:failed},null,2)+'\n');
if(failed.length) process.exit(2);
